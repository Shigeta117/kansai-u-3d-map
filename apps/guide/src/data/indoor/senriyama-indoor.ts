export function getIndoorDataStats(): {
  buildingCount: number;
  roomEntryCount: number;
  searchableCodeCount: number;
} {
  const plans = Object.values(SENRIYAMA_FLOOR_PLANS);
  let roomEntryCount = 0;
  let searchableCodeCount = 0;
  for (const p of plans) {
    roomEntryCount += p.rooms.length;
    for (const r of p.rooms) {
      searchableCodeCount += r.searchableCodes?.length ? r.searchableCodes.length : 1;
    }
  }
  return {
    buildingCount: plans.length,
    roomEntryCount,
    searchableCodeCount,
  };
}
