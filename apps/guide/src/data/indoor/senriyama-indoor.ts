function buildStandardFloors(
  levels: number,
  groundFloor: number,
  basementCount = 0,
  elevator: AccessStatus = 'unknown',
  accessibleRestroom: AccessStatus = 'unknown',
): BuildingFloorPlan['floors'] {
  const floors: BuildingFloorPlan['floors'] = [];
  for (let b = basementCount; b >= 1; b--) {
    const f = -b;
    floors.push({
      floor: f,
      label: `B${b}F`,
      groundAccess: f === groundFloor,
      elevator,
      accessibleRestroom,
    });
  }
  for (let f = 1; f <= levels; f++) {
    floors.push({
      floor: f,
      label: `${f}F`,
      groundAccess: f === groundFloor,
      elevator,
      accessibleRestroom,
    });
  }
  return floors;
}

