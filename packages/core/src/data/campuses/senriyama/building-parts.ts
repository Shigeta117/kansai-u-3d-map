/**
 * 1 つの輪郭の中で高さの違う塊に分かれる建物（読み込み時に BuildingFeature.parts を付ける）。
 *
 * - 塊の輪郭は buildings.json の輪郭の頂点と、そこから引いた切る線の点だけで作る（塊を足し合わせると元の輪郭になる）
 * - 高さは今の式（階数 × 3.8m ＋ 1.4m。building-facts.ts の heightForLevels）
 * - 地図で押して選ぶと、塊ではなく 1 つの建物として出る（塊は描き方だけ）
 */
export interface BuildingPartSpec {
  /** 塊の名前（docs と建物シートの文言用） */
  name: string;
  /** 地上の階の数 */
  levels: number;
  /** 塊の輪郭（ローカル座標 x, z。閉じない） */
  polygon: [number, number][];
}

export interface BuildingPartsSpec {
  buildingId: string;
  source: string;
  parts: BuildingPartSpec[];
  note?: string;
}

